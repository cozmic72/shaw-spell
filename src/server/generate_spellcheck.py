#!/usr/bin/env python3
"""
Generate Hunspell spell-check files for Shavian script.

Produces dialect-specific dictionaries:
  - io.joro.shaw-spell.shavian-gb.{dic,aff}
  - io.joro.shaw-spell.shavian-us.{dic,aff}

The .aff file is a static wordlist config plus the hand-curated REP table in
src/server/hunspell-replacements.txt (letter-pair swaps for basic typo
tolerance, plus directional rewrites for always-wrong decompositions of
Shavian's compound letters).

The .dic entries are augmented with Hunspell `ph:` annotations derived
from PH_RULES below. `ph:<alternate>` on a dict entry tells Hunspell: "if
the user types <alternate>, this entry is a top-ranked suggestion". Our
MAP / PHONE experiments showed Hunspell's n-gram pass silently outranks
MAP/PHONE candidates for a 77k-entry dictionary; `ph:` is the one
mechanism that reliably bubbles the canonical form to the top.

PH_RULES are applied in priority order with a cap on total variants per
word. Rules fire until the cap is hit, then later rules are skipped for
that word. This keeps disk/memory bounded while still covering all the
high-value confusion cases.

Install to ~/Library/Spelling/ for macOS spell-checking.
"""

import json
import sys
import argparse
from pathlib import Path
from collections import defaultdict


# ---- Confusion rules ----
# Applied in priority order. Each rule has `substitutes`, a list of
# (src, dst, position) tuples — all substitutes in a rule fire as a
# single group (a rule counts as one "step" against PH_CAP). Within a
# group, each substitute is tried independently and the union is taken.
#
#   position: 'any' | 'final' | 'initial'
#   dialects: set of dialects this rule applies to.
#
# Keep this list SHORT and ordered by how much value each rule adds —
# when a word hits PH_CAP variants, later rules are skipped for it.

# --- Affix flags for Shavian noun morphology ---
#
# Hunspell affixes generate plurals + possessives on the fly from singular
# noun stems, instead of bloating the .dic with every inflected form.
# Voicing rule for the sibilant suffix: 𐑩𐑟 after sibilants, 𐑕 after voiceless
# (non-sibilant) consonants, 𐑟 elsewhere.
#
# Flag assignments (single-char, the Hunspell default):
#   P — pluralise (NN1/NP0 unless uncountable). Output is also flagged R so
#       the plural can take a trailing-apostrophe possessive (𐑛𐑪𐑜𐑟 → 𐑛𐑪𐑜𐑟').
#   S — singular possessive, apostrophe-free (𐑛𐑪𐑜 → 𐑛𐑪𐑜𐑟).
#   Q — singular possessive with apostrophe (𐑛𐑪𐑜 → 𐑛𐑪𐑜'𐑟). The "camp 2"
#       writer convention; canonical apostrophe-free is generated by S.
#   R — plural possessive, trailing apostrophe only (plural already ends in
#       a sibilant, so the possessive just adds '). Applied to NN2 stems
#       directly and to P-generated plurals via the SFX P /R chain.
#
# Voicing classes (last char of stem, Shavian script):
#   voiceless non-sibilant: 𐑐 𐑑 𐑒 𐑓 𐑔   (p t k f θ)
#   sibilant:               𐑕 𐑟 𐑖 𐑠 𐑗 𐑡  (s z ʃ ʒ tʃ dʒ)
#   else (voiced consonant or vowel) takes plain 𐑟
VOICELESS_NON_SIBILANT = '𐑐𐑑𐑒𐑓𐑔'
SIBILANT = '𐑕𐑟𐑖𐑠𐑗𐑡'
ELSE_NEGATED = VOICELESS_NON_SIBILANT + SIBILANT  # used in [^...] for the catchall

PH_CAP = 8

